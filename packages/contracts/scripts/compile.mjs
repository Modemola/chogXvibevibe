// Compiles contracts/ with solc-js (bundled WASM, no downloads) into artifacts/ and src/artifacts.ts.
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const solc = require('solc');
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = path.join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : p.endsWith('.sol') ? [p] : [];
  });
}

const sources = Object.fromEntries(
  walk(path.join(root, 'contracts')).map((p) => [path.relative(root, p), { content: readFileSync(p, 'utf8') }]),
);

const input = {
  language: 'Solidity',
  sources,
  settings: {
    // Shanghai: runs on every current EVM chain, including Arbitrum Orbit chains like Robinhood Chain.
    evmVersion: 'shanghai',
    optimizer: { enabled: true, runs: 1_000 },
    outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object', 'evm.deployedBytecode.object'] } },
  },
};

function findImports(p) {
  try {
    return { contents: readFileSync(require.resolve(p), 'utf8') };
  } catch {
    return { error: `Not found: ${p}` };
  }
}

const out = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }));
const errors = (out.errors ?? []).filter((e) => e.severity === 'error');
for (const e of out.errors ?? []) console.error(e.formattedMessage);
if (errors.length) process.exit(1);

const wanted = { 'contracts/ScoutDrop.sol': ['ScoutDrop'], 'contracts/test/TestToken.sol': ['TestToken'] };
mkdirSync(path.join(root, 'artifacts'), { recursive: true });
let ts = `// Generated by scripts/compile.mjs (solc ${solc.version()}). Do not edit.\n`;
for (const [file, names] of Object.entries(wanted)) {
  for (const name of names) {
    const c = out.contracts[file][name];
    const artifact = { contractName: name, abi: c.abi, bytecode: `0x${c.evm.bytecode.object}`, compiler: solc.version() };
    writeFileSync(path.join(root, 'artifacts', `${name}.json`), JSON.stringify(artifact, null, 2));
    ts += `\nexport const ${name} = ${JSON.stringify({ abi: c.abi, bytecode: artifact.bytecode }, null, 2)} as const;\n`;
    console.log(`${name}: ${c.evm.deployedBytecode.object.length / 2} bytes deployed`);
  }
}
writeFileSync(path.join(root, 'src', 'artifacts.ts'), ts);
